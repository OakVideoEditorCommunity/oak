/// A single-footage render delivers exactly one frame and reports native
/// progress to the driver.
#[test]
fn footage_frame_is_delivered_with_progress() {
	let media = clip_path("footage");
	oak_codec::testmedia::write_test_clip(&media, 64, 64, 10, 10).expect("test clip");
	let (project, footage, params) = footage_project(&media.to_string_lossy(), 1);

	let _guard = render_serial();
	let mut task = render_task(&project, footage, Some(params));
	task.set_render_inputs(
		0,
		false,
		TimeRange::new(Rational::new(0, 1), Rational::new(1, 1)),
	);
	let progress = Arc::new(Mutex::new(Vec::new()));
	let sink = progress.clone();
	let mut driver = Task::new("render", None);
	driver.set_event_listener(Box::new(move |event| {
		if let TaskEvent::Progress(value) = event {
			sink.lock().unwrap().push(value);
		}
	}));

	let mut recorder = Recorder::new();
	assert!(task.render(&mut driver, &mut recorder).is_ok());
	assert_eq!(recorder.order, vec!["frame"]);
	assert_eq!(recorder.frames, vec![(64, 64)]);
	assert_eq!(recorder.timestamps, vec![Rational::new(0, 1)]);
	assert_eq!(
		*progress.lock().unwrap(),
		vec![1.0],
		"the native progress reaches 1.0 after the single frame"
	);
	assert!(!driver.is_cancelled());

	let _ = std::fs::remove_file(&media);
}

