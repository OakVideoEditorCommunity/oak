//! Boundary tests for the `RenderTask` base: empty ranges, stale viewer
//! nodes, hook errors, cancellation, forced sizes/formats, footage and
//! montage delivery (video + audio, audio first) and progress reporting.
//!
//! Renders run on the process-wide manager's test-only inline (`Threads`)
//! backend, serialized through one static mutex, so no GPU, no worker
//! processes and no sleeps are involved. Media is generated by
//! `oak_codec::testmedia`.

