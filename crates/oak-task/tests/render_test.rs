/// An effect in the clip's chain is walked (params collected) and its
/// enable state applied: the fixture's Opacity (factor 0) zeroes every
/// delivered channel when enabled and passes the decoded clip through when
/// disabled, so the two branches differ observably — a regression that
/// drops the chain (or ignores the enable flag) cannot pass both.
#[test]
fn clip_effect_chain_is_walked_and_bypassed() {
	let media = clip_path("effect");
	oak_codec::testmedia::write_test_clip(&media, 64, 64, 10, 10).expect("test clip");
	let _guard = render_serial();

	for enabled in [false, true] {
		let (project, sequence, params) =
			sequence_project(&media.to_string_lossy(), false, Some(enabled));

		// Fixture sanity: the clip's effect input is fed by the Opacity
		// node, and the node carries the factor-zero input the walk needs.
		let upstream_type = {
			let guard = project.lock().unwrap_or_else(|e| e.into_inner());
			let clip = guard
				.graph
				.node_ids()
				.into_iter()
				.find(|id| {
					guard
						.graph
						.get(*id)
						.and_then(|e| e.behavior.as_any())
						.and_then(|a| a.downcast_ref::<ClipBlockBehavior>())
						.is_some()
				})
				.expect("clip node");
			let input = guard.graph.get(clip).unwrap().core.effect_input.clone();
			let upstream = guard
				.graph
				.connected_output(clip, &input, -1)
				.expect("effect upstream");
			let entry = guard.graph.get(upstream).unwrap();
			assert!(
				matches!(
					entry.core.standard_value(oak_node::node::ENABLED_INPUT, -1),
					oak_node::value::NodeValue::Boolean(v) if v == enabled
				),
				"the fixture enable state"
			);
			assert!(
				matches!(
					entry.core.standard_value("opacity_in", -1),
					oak_node::value::NodeValue::Float(v) if v == 0.0
				),
				"the fixture opacity factor"
			);
			entry.behavior.type_id().to_string()
		};
		assert_eq!(upstream_type, "org.olivevideoeditor.Olive.opacity");

		let mut task = render_task(&project, sequence, Some(params));
		task.set_render_inputs(
			0,
			false,
			TimeRange::new(Rational::new(0, 1), Rational::new(1, 1)),
		);
		let mut driver = Task::new("render", None);
		let mut recorder = Recorder::new();
		assert!(task.render(&mut driver, &mut recorder).is_ok());
		assert_eq!(recorder.order, vec!["frame"]);
		assert_eq!(recorder.frames, vec![(64, 64)]);

		let pixel = recorder.first_pixels[0].expect("CPU frame with a readable pixel");
		if enabled {
			assert_eq!(
				pixel,
				[0.0, 0.0, 0.0, 0.0],
				"the enabled opacity zeroes every channel"
			);
		} else {
			assert!(
				pixel != [0.0, 0.0, 0.0, 0.0] && pixel[3] > 0.0,
				"the disabled effect must pass the decoded clip through unchanged: {pixel:?}"
			);
		}
	}

	let _ = std::fs::remove_file(&media);
}

