/// A project with one probed footage node (64x64, 1 s) and one sequence.
fn footage_project(media: &str, fps: i64) -> (ProjectRef, NodeId, VideoParams) {
	let project = Project::new();
	let (footage_id, sequence) = {
		let mut p = project.lock().unwrap();

		let mut footage = FootageBehavior::new(media);
		footage.probe().expect("probe the generated clip");
		let footage_id = p.graph.add_node(NodeCore::new(), Box::new(footage));

		let (score, sbehavior) = SequenceBehavior::create();
		let sequence = p.graph.add_node(score, sbehavior);
		if let Some(seq) = p
			.graph
			.get_mut(sequence)
			.and_then(|e| e.behavior.as_any_mut())
			.and_then(|a| a.downcast_mut::<SequenceBehavior>())
		{
			seq.video_params[0].frame_rate = Rational::new(fps, 1);
			seq.video_params[0].width = 64;
			seq.video_params[0].height = 64;
		}
		(footage_id, sequence)
	};
	let params = nodeops::sequence_video_params(&project, sequence, 0).expect("sequence params");
	(project, footage_id, params)
}

/// A sequence with one video clip (and optionally an audio clip) of the
/// same media, both covering `[0, 1s)`. With `effect = Some(enabled)`, an
/// Opacity effect (factor 0) with that enable-state sits between the
/// footage and the clip so the effect-chain walk is exercised and its
/// effect is observable in the delivered pixels: the montage evaluator
/// applies the built-in Opacity on the CPU (unknown built-ins pass
/// through without a GPU, so those could not prove the chain ran).
fn sequence_project(
	media: &str,
	with_audio: bool,
	effect: Option<bool>,
) -> (ProjectRef, NodeId, VideoParams) {
	let project = Project::new();
	let sequence = {
		let mut p = project.lock().unwrap();

		let mut footage = FootageBehavior::new(media);
		footage.probe().expect("probe the generated clip");
		let footage_id = p.graph.add_node(NodeCore::new(), Box::new(footage));

		let (score, sbehavior) = SequenceBehavior::create();
		let sequence = p.graph.add_node(score, sbehavior);
		if let Some(seq) = p
			.graph
			.get_mut(sequence)
			.and_then(|e| e.behavior.as_any_mut())
			.and_then(|a| a.downcast_mut::<SequenceBehavior>())
		{
			seq.video_params[0].frame_rate = Rational::new(1, 1);
			seq.video_params[0].width = 64;
			seq.video_params[0].height = 64;
		}

		let kinds: &[TrackType] = if with_audio {
			&[TrackType::Video, TrackType::Audio]
		} else {
			&[TrackType::Video]
		};
		for &kind in kinds {
			let (tcore, tbehavior) = TrackBehavior::create();
			let track = p.graph.add_node(tcore, tbehavior);
			p.graph
				.get_mut(track)
				.unwrap()
				.behavior
				.as_any_mut()
				.unwrap()
				.downcast_mut::<TrackBehavior>()
				.unwrap()
				.kind = kind;

			let (ccore, cbehavior) = oak_node::block::clip_create();
			let clip = p.graph.add_node(ccore, cbehavior);
			if effect.is_some() && kind == TrackType::Video {
				// The Opacity module is private; the factory is the public
				// constructor. The value input is zeroed so an enabled
				// effect zeroes every delivered channel (including alpha).
				let (ecore, ebehavior) = oak_node::factory::Factory::global()
					.create_any("org.olivevideoeditor.Olive.opacity")
					.expect("opacity node registered");
				let effect_node = p.graph.add_node(ecore, ebehavior);
				p.graph
					.get_mut(effect_node)
					.unwrap()
					.core
					.set_standard_value(
						oak_node::node::ENABLED_INPUT,
						-1,
						oak_node::value::NodeValue::Boolean(effect.unwrap_or(false)),
					);
				p.graph
					.get_mut(effect_node)
					.unwrap()
					.core
					.set_standard_value("opacity_in", -1, oak_node::value::NodeValue::Float(0.0));
				p.graph
					.connect(footage_id, effect_node, "tex_in", -1)
					.expect("connect footage to effect");
				p.graph
					.connect(
						effect_node,
						clip,
						oak_node::block::clip_input::TEXTURE_INPUT,
						-1,
					)
					.expect("connect effect to clip");
			} else {
				p.graph
					.connect(
						footage_id,
						clip,
						oak_node::block::clip_input::TEXTURE_INPUT,
						-1,
					)
					.expect("connect footage to clip");
			}
			p.graph
				.get_mut(clip)
				.unwrap()
				.behavior
				.as_any_mut()
				.unwrap()
				.downcast_mut::<ClipBlockBehavior>()
				.expect("clip block")
				.core
				.range = TimeRange::new(Rational::new(0, 1), Rational::new(1, 1));
			p.graph
				.get_mut(track)
				.unwrap()
				.behavior
				.as_any_mut()
				.unwrap()
				.downcast_mut::<TrackBehavior>()
				.unwrap()
				.append_block(clip);

			let (lcore, lbehavior) = TrackListBehavior::create();
			let list = p.graph.add_node(lcore, lbehavior);
			{
				let list_b = p
					.graph
					.get_mut(list)
					.unwrap()
					.behavior
					.as_any_mut()
					.unwrap()
					.downcast_mut::<TrackListBehavior>()
					.unwrap();
				list_b.kind = kind;
				list_b.tracks.push(track);
			}
			p.graph
				.get_mut(sequence)
				.unwrap()
				.behavior
				.as_any_mut()
				.unwrap()
				.downcast_mut::<SequenceBehavior>()
				.unwrap()
				.track_lists
				.push(list);
		}
		sequence
	};

	let params = nodeops::sequence_video_params(&project, sequence, 0).expect("sequence params");
	(project, sequence, params)
}

/// Build a `RenderTask` for `viewer` with a 64x64 forced F32 render size.
fn render_task(project: &ProjectRef, viewer: NodeId, params: Option<VideoParams>) -> RenderTask {
	let mut task = RenderTask::new(
		Task::new("render", None),
		params,
		(project.clone(), viewer),
		ForceParams {
			force_width: 64,
			force_height: 64,
			// The default leaves `force_format` off (-1), so the pipeline
			// frame stays F32.
			..ForceParams::default()
		},
		None,
	);
	task.set_max_inflight(2);
	task
}

/// The first RGBA pixel of a delivered texture as f32 (downloads GPU
/// textures; `None` when the texture cannot be read back).
fn first_pixel(frame: &Texture) -> Option<[f32; 4]> {
	let f = frame.to_frame().ok()?;
	if f.width <= 0 || f.height <= 0 || f.data.len() < 16 {
		return None;
	}
	let mut px = [0.0f32; 4];
	for (i, channel) in px.iter_mut().enumerate() {
		let start = i * 4;
		*channel = f32::from_le_bytes(f.data[start..start + 4].try_into().ok()?);
	}
	Some(px)
}

/// A `RenderTaskBehavior` recording the delivered payloads in order.
#[derive(Default)]
struct Recorder {
	order: Vec<&'static str>,
	frames: Vec<(i32, i32)>,
	/// Pixel format of each delivered frame (the forced-format contract).
	formats: Vec<PixelFormat>,
	/// First RGBA pixel of each delivered frame (effect and generated-frame
	/// observability).
	first_pixels: Vec<Option<[f32; 4]>>,
	timestamps: Vec<Rational>,
	audio_samples: Vec<usize>,
	fail_frames: bool,
	fail_audio: bool,
	/// Cancel the driving task from the first frame hook (exercises the
	/// between-frames cancellation path deterministically).
	cancel_on_first_frame: bool,
	cancelled: bool,
}

impl Recorder {
	fn new() -> Recorder {
		Recorder::default()
	}
}

impl RenderTaskBehavior for Recorder {
	fn frame_downloaded(&mut self, task: &mut Task, frame: &Texture) -> Result<()> {
		self.order.push("frame");
		self.frames.push(frame.size());
		self.formats.push(frame.format());
		self.first_pixels.push(first_pixel(frame));
		self.timestamps.push(
			frame
				.to_frame()
				.map(|f| f.timestamp)
				.unwrap_or(Rational::NULL),
		);
		if self.fail_frames {
			return Err(Error::Failed("frame hook failed".to_string()));
		}
		if self.cancel_on_first_frame && !self.cancelled {
			self.cancelled = true;
			task.cancel();
		}
		Ok(())
	}

	fn audio_downloaded(&mut self, _task: &mut Task, samples: &AudioSamples) -> Result<()> {
		self.order.push("audio");
		self.audio_samples.push(samples.samples.len());
		if self.fail_audio {
			return Err(Error::Failed("audio hook failed".to_string()));
		}
		Ok(())
	}

	fn encode_subtitle(&mut self, _task: &mut Task, _text: &str) -> Result<()> {
		Err(Error::Failed(
			"subtitles are not rendered by this test".into(),
		))
	}
}

