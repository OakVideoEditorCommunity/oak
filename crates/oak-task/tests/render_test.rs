// ---- private process dispatcher (no global manager) -------------------

/// Environment-only reason the private dispatcher cannot render here: the
/// worker pool itself could not be created or started (an unusable
/// `oak-worker`, exec denied, process-table exhaustion, ...). Everything
/// else — ticket errors, wrong payload kinds, unexpected timestamps, shm
/// conversion problems — is a product failure and must fail the test.
fn worker_pool_environment_error(error: &Error) -> bool {
	matches!(error, Error::Failed(message) if message.starts_with("render worker pool"))
}

/// Shuts the process-wide render manager down and points `OAK_WORKER_BIN`
/// at `worker` for the private-dispatcher render, restoring both on drop —
/// so a panicking render can never leak the shut-down manager or the env
/// override into later tests. [`DispatcherEnvGuard::restore`] restores
/// eagerly, before the assertions.
struct DispatcherEnvGuard {
	previous_worker_bin: Option<std::ffi::OsString>,
	restored: bool,
}

impl DispatcherEnvGuard {
	fn install(worker: &std::path::Path) -> DispatcherEnvGuard {
		let previous_worker_bin = std::env::var_os("OAK_WORKER_BIN");
		std::env::set_var("OAK_WORKER_BIN", worker);
		let guard = DispatcherEnvGuard {
			previous_worker_bin,
			restored: false,
		};
		RenderManager::shutdown();
		assert!(
			RenderManager::global().is_none(),
			"the private path needs no global manager"
		);
		guard
	}

	/// Restore the manager and the environment exactly once.
	fn restore(&mut self) {
		if self.restored {
			return;
		}
		self.restored = true;
		RenderManager::init_with_backend(RenderBackendChoice::Threads).expect("render manager");
		match self.previous_worker_bin.take() {
			Some(value) => std::env::set_var("OAK_WORKER_BIN", value),
			None => std::env::remove_var("OAK_WORKER_BIN"),
		}
	}
}

impl Drop for DispatcherEnvGuard {
	fn drop(&mut self) {
		self.restore();
	}
}

/// With the global render manager shut down, [`RenderTask::render`] stands
/// up its own process dispatcher and renders through `oak-worker`
/// processes: the `ShmFrame`/`ShmAudio` delivery seams, the poll pump and
/// the dispatcher teardown (`shm_frame_to_texture`'s BGRA8 and F32
/// branches).
///
/// Only the worker pool being unavailable is an environment skip (the
/// missing-binary case skips earlier): a pool that cannot be created or
/// started prints a reason. Every product failure — a `"Frame render
/// ticket failed"`, a bad shm payload/format, a poll timeout surfacing as
/// a ticket error — fails the test.
#[test]
fn private_dispatcher_renders_frames_and_audio_through_workers() {
	let _guard = render_serial();
	let Some(worker) = locate_oak_worker() else {
		eprintln!("oak-worker binary not built; skipping the private dispatcher render");
		return;
	};

	let media = clip_path("private");
	oak_codec::testmedia::write_test_clip(&media, 64, 64, 10, 10).expect("test clip");

	// The dispatcher resolves the worker binary from the environment when
	// it is constructed by the render call below. The guard restores the
	// manager and the env also when a render panics.
	let mut env = DispatcherEnvGuard::install(&worker);

	// Audio + video through the workers (the default BGRA8 wire format).
	let (project, sequence, params) = sequence_project(&media.to_string_lossy(), true, None);
	let mut task = render_task(&project, sequence, Some(params));
	task.set_max_inflight(2);
	task.set_render_inputs(
		0,
		true,
		TimeRange::new(Rational::new(0, 1), Rational::new(1, 1)),
	);
	let mut driver = Task::new("render", None);
	let mut recorder = Recorder::new();
	let outcome = task.render(&mut driver, &mut recorder);

	// A forced F32 ticket takes the no-conversion shm branch.
	let (fproject, footage, _) = footage_project(&media.to_string_lossy(), 1);
	let mut f32_task = render_task(&fproject, footage, None);
	f32_task.force_params.force_format = PixelFormat::F32 as i32;
	f32_task.set_render_inputs(
		0,
		false,
		TimeRange::new(Rational::new(0, 1), Rational::new(1, 1)),
	);
	let mut f32_driver = Task::new("render", None);
	let mut f32_recorder = Recorder::new();
	let f32_outcome = f32_task.render(&mut f32_driver, &mut f32_recorder);

	// Restore the manager and the environment before asserting.
	env.restore();

	let mut skipped_environment = Vec::new();
	match outcome {
		Ok(()) => {
			assert_eq!(
				recorder.order,
				vec!["audio", "frame"],
				"the worker audio and frame land in order"
			);
			assert_eq!(recorder.frames, vec![(64, 64)]);
			assert_eq!(
				recorder.formats,
				vec![PixelFormat::F32],
				"the BGRA8 wire frame is converted to the F32 delivery format"
			);
			assert!(recorder.audio_samples[0] > 0);
		}
		Err(error) if worker_pool_environment_error(&error) => {
			eprintln!("private dispatcher worker pool unavailable: {error}; skipping");
			skipped_environment.push("video+audio");
		}
		Err(error) => panic!("the private dispatcher render failed (product error): {error}"),
	}
	match f32_outcome {
		Ok(()) => {
			assert_eq!(f32_recorder.frames, vec![(64, 64)]);
			assert_eq!(
				f32_recorder.formats,
				vec![PixelFormat::F32],
				"the forced F32 shm branch keeps the delivery format"
			);
		}
		Err(error) if worker_pool_environment_error(&error) => {
			eprintln!("private dispatcher F32 render unavailable: {error}; skipping");
			skipped_environment.push("f32");
		}
		Err(error) => panic!("the private dispatcher F32 render failed (product error): {error}"),
	}
	if !skipped_environment.is_empty() {
		eprintln!(
			"private dispatcher render skipped (environment unavailable): {}",
			skipped_environment.join(", ")
		);
	}

	let _ = std::fs::remove_file(&media);
}

