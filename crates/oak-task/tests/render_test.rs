/// A default-constructed render task exposes zero frames and every
/// configurator tolerates edge values. The window/progress configurators
/// have no getters; their observable effects are covered by
/// [`max_inflight_edges_still_deliver`] and
/// [`native_progress_signalling_can_be_disabled`].
#[test]
fn new_defaults_and_configurators_accept_edges() {
	let project = Project::new();
	let mut task = RenderTask::new(
		Task::new("render", None),
		None,
		(project, NodeId::INVALID),
		ForceParams::default(),
		None,
	);
	assert_eq!(task.total_frames(), 0);
	assert!(!task.force_params.has_force_matrix);
	// Defaults must leave every override off (-1, not 0 = U8).
	assert_eq!(task.force_params.force_format, -1);
	task.set_render_inputs(0, true, TimeRange::default());
	task.set_native_progress_signalling(false);
	task.set_max_inflight(0);
	task.set_max_inflight(usize::MAX);
	assert_eq!(task.total_frames(), 0, "configuring does not plan frames");
	assert_eq!(
		task.force_params.force_format, -1,
		"configuring keeps defaults"
	);
}

/// The edge in-flight windows (`0`, `usize::MAX`) still render: the loop
/// clamps the window to at least one ticket. There is no `max_inflight`
/// getter, so the delivered frame is the observable effect.
#[test]
fn max_inflight_edges_still_deliver() {
	let media = clip_path("inflight");
	oak_codec::testmedia::write_test_clip(&media, 64, 64, 10, 10).expect("test clip");
	let (project, footage, params) = footage_project(&media.to_string_lossy(), 1);

	let _guard = render_serial();
	for max in [0usize, usize::MAX] {
		let mut task = render_task(&project, footage, Some(params.clone()));
		task.set_max_inflight(max);
		task.set_render_inputs(
			0,
			false,
			TimeRange::new(Rational::new(0, 1), Rational::new(1, 1)),
		);
		let mut driver = Task::new("render", None);
		let mut recorder = Recorder::new();
		assert!(
			task.render(&mut driver, &mut recorder).is_ok(),
			"max_inflight {max} must still render"
		);
		assert_eq!(
			recorder.frames,
			vec![(64, 64)],
			"max_inflight {max} delivers the frame"
		);
	}

	let _ = std::fs::remove_file(&media);
}

