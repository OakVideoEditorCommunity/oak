/// The manager is process-wide and the inline backend is test-only.
static RENDER_LOCK: Mutex<()> = Mutex::new(());

/// Serialize render-manager use and make sure the inline backend is up.
fn render_serial() -> MutexGuard<'static, ()> {
	let guard = RENDER_LOCK.lock().unwrap_or_else(|e| e.into_inner());
	if RenderManager::global().is_none() {
		RenderManager::init_with_backend(RenderBackendChoice::Threads).expect("render manager");
	}
	guard
}

fn clip_path(tag: &str) -> std::path::PathBuf {
	std::env::temp_dir().join(format!("oaktask_render_{tag}_{}.mp4", std::process::id()))
}

/// Locate an `oak-worker` binary for the private-dispatcher path: an
/// explicit `OAK_WORKER_BIN`, a sibling of the test executable, or the
/// workspace `target/<profile>/oak-worker`. `None` means the path is
/// unavailable in this environment (the test then skips with a reason).
fn locate_oak_worker() -> Option<std::path::PathBuf> {
	if let Some(var) = std::env::var_os("OAK_WORKER_BIN") {
		let path = std::path::PathBuf::from(var);
		if path.is_file() {
			return Some(path);
		}
	}
	if let Some(dir) = std::env::current_exe().ok().and_then(|e| e.parent().map(|p| p.to_path_buf())) {
		let path = dir.join("oak-worker");
		if path.is_file() {
			return Some(path);
		}
	}
	let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
	for profile in ["debug", "release"] {
		let path = manifest.join("../../target").join(profile).join("oak-worker");
		if path.is_file() {
			return Some(path);
		}
	}
	None
}

